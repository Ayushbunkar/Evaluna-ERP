// Define the shape of the data needed to create a new user (from Super Admin UI)
export interface NewUserParams {
	fullName: string;
	employeeId: string;
	email: string;
	roleName: Role;
	branchId: number;
	warehouseId?: number;
	initialPassword?: string;
	forcePasswordChange: boolean;
	actorId: string; // The ID of the Super Admin performing the action
}

// Define the possible statuses for the user account (from auth-schema.ts)
export type UserStatus = InferInsertModel<typeof user>["status"];

